/** 把经纬度折线投到「世界单位」坐标（1 单位 ≈ 1 纬度） */
function project(pts) {
  return pts.map(([lon, lat]) => [(lon - 73.5) * 0.82, 54.2 - lat]);
}

/** 构建骑行路径：平滑坐标 + 累计弧长。返回 { pts, cum, total } */
export function buildRoute() {
  const pts = project(ROUTE);
  const cum = [0];
  for (let i = 1; i < pts.length; i++) {
    const [x0, y0] = pts[i - 1];
    const [x1, y1] = pts[i];
    cum.push(cum[i - 1] + Math.hypot(x1 - x0, y1 - y0));
  }
  // 闭合：最后一段回到起点
  const [x0, y0] = pts[pts.length - 1];
  const [x1, y1] = pts[0];
  cum.push(cum[cum.length - 1] + Math.hypot(x1 - x0, y1 - y0));
  return { pts, cum, total: cum[cum.length - 1] };
}

/** 距离 d 处的位置与朝向（单位向量） */
export function pointAt(route, d) {
  const { pts, cum, total } = route;
  let dd = ((d % total) + total) % total;
  let i = 1;
  while (i < cum.length && cum[i] < dd) i++;
  const t = (dd - cum[i - 1]) / (cum[i] - cum[i - 1] || 1);
  const a = pts[i - 1];
  const b = pts[i % pts.length];
  return {
    x: a[0] + (b[0] - a[0]) * t,
    y: a[1] + (b[1] - a[1]) * t,
    dx: b[0] - a[0], dy: b[1] - a[1],
    idx: i % pts.length
  };
}

/** 装饰岛屿也投到世界坐标 */
export function buildIslands() {
  return ISLANDS.map((poly) => project(poly));
}
